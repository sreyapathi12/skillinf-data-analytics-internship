-- Sample (synthetic) dataset: 120 students, 5 subjects, 600 result rows.
-- Written for SQLite; also runs in MySQL/PostgreSQL with minor type changes.

DROP TABLE IF EXISTS results;
DROP TABLE IF EXISTS subjects;
DROP TABLE IF EXISTS students;

CREATE TABLE students (
    student_id TEXT PRIMARY KEY,          -- anonymous ID, no names
    section    TEXT NOT NULL CHECK (section IN ('A','B','C','D'))
);

CREATE TABLE subjects (
    subject_id   INTEGER PRIMARY KEY,
    subject_name TEXT NOT NULL UNIQUE
);

CREATE TABLE results (
    student_id       TEXT    NOT NULL REFERENCES students(student_id),
    subject_id       INTEGER NOT NULL REFERENCES subjects(subject_id),
    marks            INTEGER NOT NULL CHECK (marks BETWEEN 0 AND 100),
    classes_held     INTEGER NOT NULL CHECK (classes_held > 0),
    classes_attended INTEGER NOT NULL CHECK (classes_attended BETWEEN 0 AND classes_held),
    PRIMARY KEY (student_id, subject_id)  -- one result per student per subject
);

